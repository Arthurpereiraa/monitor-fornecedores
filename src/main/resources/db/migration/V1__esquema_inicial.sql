-- Esquema inicial. SQL compatível com PostgreSQL (produção) e H2 em modo PostgreSQL (desenvolvimento e testes).

create table fornecedor (
    id             bigint generated by default as identity primary key,
    cnpj           varchar(14)  not null unique,
    razao_social   varchar(255),
    nome_fantasia  varchar(255),
    situacao       varchar(40),
    municipio      varchar(120),
    uf             varchar(2),
    nivel_risco    varchar(10)  not null,
    fonte          varchar(30),
    cadastrado_em  timestamp with time zone not null,
    verificado_em  timestamp with time zone not null
);

create index idx_fornecedor_nivel_risco on fornecedor (nivel_risco);

create table avaliacao (
    id              bigint generated by default as identity primary key,
    fornecedor_id   bigint       not null references fornecedor (id) on delete cascade,
    nivel_risco     varchar(10)  not null,
    nivel_anterior  varchar(10),
    fonte           varchar(30),
    avaliado_em     timestamp with time zone not null
);

create index idx_avaliacao_fornecedor on avaliacao (fornecedor_id, avaliado_em);

create table avaliacao_alerta (
    avaliacao_id  bigint        not null references avaliacao (id) on delete cascade,
    ordem         integer       not null,
    nivel         varchar(10)   not null,
    codigo        varchar(40)   not null,
    mensagem      varchar(500)  not null,
    primary key (avaliacao_id, ordem)
);
